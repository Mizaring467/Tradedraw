#!/usr/bin/env python3
"""C1/C2 conservative content-based classifications; never approve unknown provenance."""
import datetime
import hashlib
import json
from pathlib import Path
from scripts.research.inventory import parse

ROOT = Path.cwd()
BASE = '4fdb6466d5005499789d801d64916ea9c15421a3'


def write_once(path, value):
    payload = json.dumps(value, sort_keys=True, indent=2, ensure_ascii=False) + '\n'
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        if path.read_text() != payload:
            raise ValueError(f'Immutable manifest conflict: {path}')
    else:
        path.write_text(payload)


def classify(record):
    path=Path(record['path'])
    schema=set(record['schema'])
    evidence=[]
    classification='UNKNOWN'
    quality='INSUFFICIENT_METADATA'
    parents=[]
    if {'mode','summary','pairs','divergence_breakdown'} <= schema or {'decision_id','first_divergence','live','replay'} <= schema:
        classification='REPORT_DERIVED';quality='VALID_FOR_DIAGNOSTICS_ONLY'
        evidence=['Content contains matched comparison report, not raw prices. scripts/validation/compare_live_replay.py']
    elif 'tick_rows' in record:
        # Validate companion device records; producer alone cannot prove arbitrary files are live.
        companion=path.parent/'live_samples.jsonl'
        if companion.exists():
            samples,_,_,_=parse(companion,companion.read_bytes())
            device=[r.get('status',{}) for r in samples if isinstance(r,dict)]
            if any(s.get('app')=='TradeDraw' and s.get('gitSha') and 'isDemoAccount' in s for s in device):
                classification='BROKER_DEVICE_CAPTURE';quality='VALID_FOR_DIAGNOSTICS_ONLY'
                evidence=['ts/ric/price content; companion timestamped TradeDraw status with observed APK SHA/account state.',
                          'Producer scripts/validation/live_monitor_r23_autonomous.py:953-963,1465-1495 (timestamp-keyed, buffer-limited, prunes warmup).',
                          'No source-clock contract, complete warmup, or verified historical invocation; not research-approved.']
                parents=[str(companion)]
    elif {'sample_idx','timestamp_ms','status'} <= schema or {'app','analysis','gitSha','isDemoAccount'} <= schema:
        classification='BROKER_DEVICE_CAPTURE';quality='VALID_FOR_DIAGNOSTICS_ONLY'
        evidence=['TradeDraw device/status payload content, generated by live_monitor_r23_autonomous.py. Polls are not independent decisions.']
    elif {'counterfactual_id','entry_price','expiry_ts','theoretical_ev'} <= schema:
        classification='REPLAY_DERIVED';quality='VALID_FOR_DIAGNOSTICS_ONLY'
        evidence=['Content is counterfactual outcome after veto, not executed trade. Monitor nearest-tick settlement is diagnostic only.']
        parents=[str(path.parent/'decisions.csv'),str(path.parent/'ticks_live.csv')]
    elif {'action','similarity','sim_pct','strategy','timestamp'} <= schema:
        classification='REPLAY_DERIVED';quality='VALID_FOR_DIAGNOSTICS_ONLY'
        evidence=['Replay adaptive-block diagnostic schema; ReplayBacktestTest writes this projection.']
        parents=[str(path.parent/'ticks_live.csv')]
    elif {'action','reason','result','submode','strategy'} <= schema:
        try:
            rows,_,_,_=parse(path,path.read_bytes())
        except Exception:
            rows=[]
        if rows and all(r.get('strategy')=='REPLAY' and r.get('submode')=='BACKTEST' for r in rows):
            classification='REPLAY_DERIVED';quality='VALID_FOR_DIAGNOSTICS_ONLY'
            evidence=['Content REPLAY/BACKTEST equals scripts/backtest/replay.py run output. Raw historical input absent; no strategy edge.']
    # Direct generator evidence, not merely a directory name.
    if str(path) in {'data/fixtures/r21/fixture_live_decisions.csv','data/fixtures/r21/fixture_replay_decisions.csv'}:
        classification='FIXTURE';quality='FIXTURE_ONLY'
        evidence=['compare_live_replay.py save_fixture_to_csv explicitly generates this pair for fixture mode.']
    return classification,quality,evidence,parents


def main():
    records=json.loads(Path('loops/r29c/evidence/c0/inventory_v1.json').read_text())
    catalog=[]
    for r in records:
        classification,quality,evidence,parents=classify(r)
        m=dict(dataset_id=r['dataset_id'],version=1,sha256=r['sha256'],classification=classification,
               source=r['path'],rows=r['rows'],start=r['timestamp_min_ms'],end=r['timestamp_max_ms'],
               assets=r['assets'],derived_from=[dict(path=p,sha256=hashlib.sha256(Path(p).read_bytes()).hexdigest() if Path(p).exists() else None,relationship='CANDIDATE_COMPANION_OR_INPUT_NOT_PROVEN_CAUSAL') for p in parents],
               quality_status=quality,provenance_evidence=evidence or ['No verified producer/content chain; withheld.'],
               audit_git_sha=BASE,byte_identical_paths=r['byte_identical_paths'])
        catalog.append(m)
        # Every potentially usable observation source gets its own versioned immutable manifest.
        if classification in {'BROKER_DEVICE_CAPTURE','FIXTURE'} or 'tick_rows' in r:
            write_once(Path('datasets/manifests')/(r['dataset_id']+'.v1.json'),m)
    write_once(Path('datasets/manifests/catalog.v1.json'),catalog)
    from collections import Counter
    print(Counter(m['classification'] for m in catalog))
    print(Counter(m['quality_status'] for m in catalog))

if __name__=='__main__':
    main()
